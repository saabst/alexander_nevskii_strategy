import type { ChronicleVerdict } from '@nevsky/core';

/**
 * Слова для итога о ходе князя.
 *
 * Живут в веб-слое, а не в ядре: ядро решает, что известно, а как это
 * назвать человеку — дело интерфейса.
 *
 * Три состояния разведены нарочно. «Так не было» — это знание, оно опирается
 * на источник, где сказано, как было. «Летопись молчит» — это незнание, и
 * выдавать его за знание нельзя: половина событий кампании именно такова.
 */
export interface ChronicleMeta {
  /** как это назвать одним словом */
  label: string;
  /** что это значит */
  hint: string;
  color: string;
  /** знак в тесной строке: в списке решений слова не помещаются */
  mark: string;
}

